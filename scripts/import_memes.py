"""One-shot import of https://huggingface.co/datasets/not-lain/meme-dataset (300 memes).

Downloads the images into src/main/resources/static/memes/ (served by Spring at /memes/...)
and generates initdb/3_CARDS.sql. Outputs are committed: only rerun to rebuild them.
Stdlib only:  python3 scripts/import_memes.py
"""
import json
import random
import urllib.request
from pathlib import Path

API = "https://datasets-server.huggingface.co/rows?dataset=not-lain/meme-dataset&config=default&split=train"
ROOT = Path(__file__).resolve().parent.parent
IMG_DIR = ROOT / "src/main/resources/static/memes"
SQL_FILE = ROOT / "initdb/3_CARDS.sql"

# How many of the 300 cards get each rarity (must sum to the dataset size).
RARITY_COUNTS = {"COMMON": 100, "UNCOMMON": 75, "RARE": 55, "VERY_RARE": 40, "ULTRA_RARE": 20, "SECRET": 10}
SEED = 42  # fixed so a rerun gives every meme the same rarity


def fetch_rows():
    rows, offset = [], 0
    while True:
        with urllib.request.urlopen(f"{API}&offset={offset}&length=100") as r:
            page = json.load(r)["rows"]
        if not page:
            return rows
        rows += page
        offset += len(page)


def main():
    rows = fetch_rows()
    assert sum(RARITY_COUNTS.values()) == len(rows), f"RARITY_COUNTS must sum to {len(rows)}"
    rarities = [r for r, n in RARITY_COUNTS.items() for _ in range(n)]
    random.Random(SEED).shuffle(rarities)

    IMG_DIR.mkdir(parents=True, exist_ok=True)
    values = []
    for row, rarity in zip(rows, rarities):
        slug = row["row"]["name"]
        file = IMG_DIR / f"{slug}.jpg"
        if not file.exists():
            urllib.request.urlretrieve(row["row"]["image"]["src"], file)
        name = slug.replace("-", " ").title().replace("'", "''")
        values.append(f"    ({row['row_idx']}, '{name}', '/memes/{slug}.jpg', '{rarity}')")

    SQL_FILE.write_text(
        "-- Generated by scripts/import_memes.py, do not edit by hand.\n"
        "INSERT INTO meme_card (source_index, name, image_url, rarity) VALUES\n"
        + ",\n".join(values) + ";\n"
    )
    print(f"{len(values)} cards -> {SQL_FILE.relative_to(ROOT)}, images in {IMG_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
